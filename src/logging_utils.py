"""
Утилиты для безопасного логирования: маскирование API-ключей.
"""


def mask_key(key: str) -> str:
    """Заменяет середину ключа звёздочками, оставляя первые и последние 4 символа."""
    if not key:
        return "***"
    if len(key) <= 8:
        return "***"
    return key[:4] + "***" + key[-4:]
